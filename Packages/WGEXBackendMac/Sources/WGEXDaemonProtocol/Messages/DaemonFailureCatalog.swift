/// One row joins backend codes, the unchanged wire representation, shell errors and CLI exits.
public struct DaemonFailurePresentation: Sendable {
    /// Nil means the controller's measured protection failure supplies the wire refusal.
    public let wireError: DaemonError?
    /// Fixed shell-facing category.
    public let tunnelError: TunnelError
    /// Stable command-line error name.
    public let cliName: String
    /// Stable command-line exit status (M1-08b/M1-12).
    public let cliExitCode: Int32
    /// Existing allowlisted lab diagnostic type, retained as fixed vocabulary.
    public let diagnosticType: String
    /// Existing allowlisted lab diagnostic case, retained as fixed vocabulary.
    public let diagnosticLabel: String

    package init(
        _ wire: DaemonError?,
        _ tunnel: TunnelError,
        _ name: String,
        _ exit: Int32,
        _ type: String = "UnknownError",
        _ label: String = "withheld",
    ) {
        wireError = wire; tunnelError = tunnel; cliName = name; cliExitCode = exit
        diagnosticType = type; diagnosticLabel = label
    }
}

