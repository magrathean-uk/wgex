#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Writes Packages/WGEXCore/Sources/WGEXCore/Generated/BuildIdentifiers.generated.swift
# (git-ignored) from WGEX_BUNDLE_ID_BASE and WGEX_TEAM (plan 03 §3, ADR-016).
#
# Inside Xcode (scheme build pre-action with a settings target) the values come
# from the build environment. From the command line pass the configuration:
#   generate-build-identifiers.sh --configuration Debug|Release
# The file is rewritten only when its content changes.
set -euo pipefail
# shellcheck source=Config/Scripts/lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

if [[ "${1:-}" == "--configuration" ]]; then
  configuration="$(configuration_name "${2:?--configuration needs Debug or Release}")"
  base="$(xcconfig_value WGEX_BUNDLE_ID_BASE "$configuration")"
  team="$(xcconfig_value WGEX_TEAM "$configuration")"
else
  base="${WGEX_BUNDLE_ID_BASE:?WGEX_BUNDLE_ID_BASE is not set (run from Xcode or pass --configuration)}"
  team="${WGEX_TEAM:?WGEX_TEAM is not set}"
fi

if [[ ! "$base" =~ ^[A-Za-z0-9][A-Za-z0-9.-]*$ ]]; then
  echo "generate-build-identifiers: invalid WGEX_BUNDLE_ID_BASE" >&2
  exit 1
fi
if [[ ! "$team" =~ ^[A-Z0-9]{10}$ ]]; then
  echo "generate-build-identifiers: invalid WGEX_TEAM" >&2
  exit 1
fi

out="$WGEX_ROOT/Packages/WGEXCore/Sources/WGEXCore/Generated/BuildIdentifiers.generated.swift"
content="// Generated by Config/Scripts/generate-build-identifiers.sh before every build.
// Do not edit; this file is git-ignored.
#if WGEX_GENERATED_IDENTIFIERS
    /// Values behind \`BuildIdentifiers.current\` for this build.
    package enum BuildIdentifierSource {
        /// \`WGEX_BUNDLE_ID_BASE\` of the configuration being built.
        package static let bundleIDBase = \"$base\"
        /// \`WGEX_TEAM\`.
        package static let team = \"$team\"
        /// True: these values come from the build settings.
        package static let isGenerated = true
    }
#endif"

if [[ -f "$out" ]] && [[ "$(cat "$out")" == "$content" ]]; then
  exit 0
fi
mkdir -p "$(dirname "$out")"
# Same-directory rename stays atomic even when TMPDIR is on another volume.
tmp="$(mktemp "$out.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
printf '%s\n' "$content" >"$tmp"
mv -f "$tmp" "$out"
echo "generate-build-identifiers: wrote BuildIdentifiers.generated.swift ($base)"
