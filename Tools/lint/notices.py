"""Generate THIRD_PARTY_NOTICES.md from Vendor/PATCHES.md and go-licenses.

Run as `python3 -I Tools/lint/notices.py [--check] [--output PATH]`.

Default: write THIRD_PARTY_NOTICES.md at the repository root.
--check: verify test-support notices and the ledger (every listed file exists; every row whose
         Modifications cell is "none yet" still matches its SHA-256; every file
         under an origin directory is listed) and write nothing.
--output PATH: write somewhere else ("-" for stdout).

Sources:
  * Vendor/PATCHES.md (Files table) plus each origin's licence text.
  * `go-licenses report` in Engine/go (distributed) and Tools/testpeer
    (test-only, listed separately as not distributed). If the module is absent
    or go-licenses fails, a clearly marked placeholder section is emitted and
    the exit status stays 0.

Standard library only. The output is deterministic (no timestamps).
"""

from __future__ import annotations

import argparse
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VENDOR = ROOT / "Vendor"
LEDGER = VENDOR / "PATCHES.md"
OWN_MODULE_PREFIX = "github.com/magrathean-uk/wgex"
GO_TEMPLATE = "{{range .}}{{.Name}}\t{{.Version}}\t{{.LicenseName}}\t{{.LicenseURL}}\n{{end}}"

# Default go-licenses reports omit these build-tag-only dependencies.
TEST_MODULES = {
    "gvisor.dev/gvisor": ("Apache-2.0", "5af94223052169198cfa2195455b7d87209d9aa0fff4705822f328b4b272facb"),
    "github.com/google/btree": ("Apache-2.0", "cfc7749b96f63bd31c3c42b5c471bf756814053e847c10f3eb003417bc523d30"),
    "golang.org/x/time": ("BSD-3-Clause", "911f8f5782931320f5b8d1160a76365b83aea6447ee6c04fa6d5591467db9dad"),
}

# Vendored modules compiled only for Windows targets (never linked into a shipped product).
WINDOWS_MODULES = {
    "golang.zx2c4.com/wintun": "MIT",
}

# Licence file per origin directory, used for the embedded texts.
LICENCE_FILES = {
    "wireguard-apple": "COPYING",
    "wombat-vpn": "LICENSE",
    "firezone": "LICENSE",
}

HEADER = """# Third-party notices

<!-- Generated by Tools/lint/notices.py from Vendor/PATCHES.md and go-licenses. Do not edit. -->

WGEX is MIT-licensed (see `LICENSE`). It includes the third-party material
listed below. Licence texts are reproduced in full for vendored source; Go
module licences are listed with their SPDX names and canonical URLs.

"WireGuard" is a registered trademark of Jason A. Donenfeld. WGEX is not
affiliated with or endorsed by the WireGuard project.
"""


class LedgerError(Exception):
    pass


def parse_ledger() -> list[dict[str, str]]:
    """Return one dict per row of the Files table in Vendor/PATCHES.md."""
    if not LEDGER.is_file():
        raise LedgerError(f"missing {LEDGER.relative_to(ROOT)}")
    lines = LEDGER.read_text(encoding="utf-8").splitlines()
    try:
        start = lines.index("## Files")
    except ValueError as exc:
        raise LedgerError("PATCHES.md has no '## Files' section") from exc
    table: list[list[str]] = []
    for line in lines[start + 1 :]:
        if line.startswith("## "):
            break
        if line.startswith("|"):
            table.append([c.strip().strip("`") for c in line.strip().strip("|").split("|")])
    if len(table) < 3:
        raise LedgerError("PATCHES.md Files table is empty")
    header = table[0]
    rows = []
    for cells in table[2:]:
        if len(cells) != len(header):
            raise LedgerError(f"ledger row has {len(cells)} cells, expected {len(header)}: {cells[0]}")
        rows.append(dict(zip(header, cells, strict=True)))
    required = {"File", "Origin repo", "Commit", "Licence", "Destination package", "Status", "Modifications", "SHA-256 (as vendored)"}
    missing = required - set(header)
    if missing:
        raise LedgerError(f"ledger columns missing: {sorted(missing)}")
    return rows


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def check_ledger(rows: list[dict[str, str]]) -> list[str]:
    problems: list[str] = []
    listed = set()
    for row in rows:
        rel = row["File"]
        listed.add(rel)
        path = VENDOR / rel
        for col in ("Origin repo", "Commit", "Licence", "Destination package", "Status", "Modifications"):
            if not row[col]:
                problems.append(f"{rel}: empty '{col}' cell")
        if not path.is_file():
            problems.append(f"{rel}: listed but not present under Vendor/")
            continue
        if row["Modifications"].lower().startswith("none") and sha256(path) != row["SHA-256 (as vendored)"]:
            problems.append(f"{rel}: content differs from the ledger SHA-256 but Modifications says none")
    for origin in LICENCE_FILES:
        if not (VENDOR / origin / "NOTICE").is_file():
            problems.append(f"Vendor/{origin}/NOTICE missing")
    for path in sorted(p for p in VENDOR.rglob("*") if p.is_file()):
        rel = path.relative_to(VENDOR).as_posix()
        if rel in listed or rel == "PATCHES.md" or path.name == "NOTICE" or path.name == ".DS_Store":
            continue
        problems.append(f"{rel}: present under Vendor/ but not in the ledger")
    return problems


def vendored_section(rows: list[dict[str, str]]) -> str:
    out = ["## Vendored source\n"]
    by_origin: dict[str, list[dict[str, str]]] = {}
    for row in rows:
        by_origin.setdefault(row["File"].split("/", 1)[0], []).append(row)
    for origin in sorted(by_origin):
        group = by_origin[origin]
        first = group[0]
        sources = [r for r in group if r["File"] not in {f"{origin}/{LICENCE_FILES.get(origin, '')}"}]
        out.append(f"### {origin}\n")
        out.append(f"- Origin: {first['Origin repo']}")
        out.append(f"- Commit: `{first['Commit']}` (full pin in `Vendor/PATCHES.md`)")
        out.append(f"- Licence: {first['Licence']}")
        out.append(f"- Files: {len(sources)} vendored, modifications: " + ("none" if all(r["Modifications"].lower().startswith("none") for r in group) else "see `Vendor/PATCHES.md`"))
        out.append("")
        for r in sources:
            out.append(f"  - `Vendor/{r['File']}`")
        out.append("")
        notice = VENDOR / origin / "NOTICE"
        lic = VENDOR / origin / LICENCE_FILES.get(origin, "LICENSE")
        if notice.is_file():
            out.append("Origin notice (`Vendor/%s/NOTICE`):\n" % origin)
            out.append("```text\n" + notice.read_text(encoding="utf-8").rstrip() + "\n```\n")
        if lic.is_file():
            out.append(f"Licence text (`Vendor/{origin}/{lic.name}`):\n")
            out.append("```text\n" + lic.read_text(encoding="utf-8").rstrip() + "\n```\n")
    return "\n".join(out)


def go_env(module_dir: Path) -> dict[str, str]:
    env = dict(os.environ)
    env["GOTOOLCHAIN"] = "local"
    env["GOPROXY"] = "off"
    env["GOWORK"] = "off"
    env["GOFLAGS"] = "-mod=vendor" if (module_dir / "vendor").is_dir() else "-mod=readonly"
    goroot = local_goroot(env)
    if goroot:
        env["GOROOT"] = goroot
    return env


def local_goroot(env: dict[str, str]) -> str:
    """GOROOT of the local toolchain, or "" when it cannot be found.

    go-licenses needs GOROOT to classify standard-library packages, and the gate
    wrapper drops it from the environment, so ask the local `go` for it (no
    network: GOTOOLCHAIN=local is already in env). An existing valid GOROOT in the
    caller's environment is kept as it is.
    """
    current = env.get("GOROOT", "")
    if current and Path(current).is_dir():
        return current
    go = shutil.which("go", path=env.get("PATH"))
    if go is None:
        return ""
    probe = {k: v for k, v in env.items() if k != "GOROOT"}
    try:
        proc = subprocess.run([go, "env", "GOROOT"], env=probe, capture_output=True, text=True, timeout=60, check=False)
    except (OSError, subprocess.TimeoutExpired):
        return ""
    found = proc.stdout.strip()
    return found if proc.returncode == 0 and found and Path(found).is_dir() else ""


def vendored_versions(module_dir: Path) -> list[tuple[str, str]]:
    """Module versions from vendor/modules.txt, longest module path first."""
    modules = module_dir / "vendor" / "modules.txt"
    found: list[tuple[str, str]] = []
    if modules.is_file():
        for line in modules.read_text(encoding="utf-8").splitlines():
            parts = line.split()
            if len(parts) >= 3 and parts[0] == "#" and not parts[1].startswith("#"):
                found.append((parts[1], parts[2]))
    return sorted(found, key=lambda mv: -len(mv[0]))


def go_licences(rel_dir: str) -> tuple[list[tuple[str, str, str, str]] | None, str]:
    """Return (rows, note). rows is None when unavailable; note says why."""
    module_dir = ROOT / rel_dir
    if not (module_dir / "go.mod").is_file():
        return None, f"{rel_dir}/go.mod does not exist yet"
    tool = shutil.which("go-licenses")
    if tool is None:
        return None, "go-licenses is not on PATH"
    with tempfile.TemporaryDirectory(prefix="wgex-notices.") as tmp:
        tpl = Path(tmp) / "report.tpl"
        tpl.write_text(GO_TEMPLATE, encoding="utf-8")
        try:
            proc = subprocess.run(
                [tool, "report", "./...", "--template", str(tpl), "--ignore", OWN_MODULE_PREFIX],
                cwd=module_dir,
                env=go_env(module_dir),
                capture_output=True,
                text=True,
                timeout=300,
                check=False,
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            return None, f"go-licenses could not run: {type(exc).__name__}"
    if proc.returncode != 0:
        first = next((ln for ln in proc.stderr.splitlines() if ln.startswith("E")), "")
        return None, f"go-licenses exited {proc.returncode} in {rel_dir}" + (f" ({first[:160]})" if first else "")
    versions = vendored_versions(module_dir)
    rows = []
    for line in proc.stdout.splitlines():
        parts = line.split("\t")
        if len(parts) != 4 or parts[0].startswith(OWN_MODULE_PREFIX):
            continue
        name, version, lic, url = parts
        if version == "Unknown":
            version = next((v for m, v in versions if name == m or name.startswith(m + "/")), version)
        if "/vendor/" in url:
            # In -mod=vendor mode go-licenses invents a URL inside this repository; use the repo path.
            url = f"{rel_dir}/vendor/" + url.split("/vendor/", 1)[1]
        rows.append((name, version, lic, url))
    return sorted(set(rows)), ""


def go_table(rows: list[tuple[str, str, str, str]]) -> str:
    if not rows:
        return "_No third-party Go packages reported._\n"
    lines = ["| Module or package | Version | Licence | Licence URL |", "|---|---|---|---|"]
    for name, version, lic, url in rows:
        lines.append(f"| `{name}` | `{version}` | {lic} | {url} |")
    return "\n".join(lines) + "\n"


def go_section(title: str, rel_dir: str, preface: str) -> str:
    rows, note = go_licences(rel_dir)
    out = [f"## {title}\n", preface + "\n"]
    if rows is None:
        out.append(f"> **PLACEHOLDER: Go licence report unavailable.** {note}. Regenerate with `python3 -I Tools/lint/notices.py` once the module builds; do not ship this file as it stands.\n")
    else:
        out.append(go_table(rows))
        if any(r[2] == "Unknown" for r in rows):
            out.append("> **Warning:** at least one package above has an unidentified licence; resolve before release.\n")
    return "\n".join(out)


def engine_test_section() -> str:
    """Explicit notices for wgextest-only modules omitted by go-licenses' default build."""
    module_dir = ROOT / "Engine/go"
    versions = dict(vendored_versions(module_dir))
    out = ["## Go engine test support (not distributed)\n",
           "These vendored modules are reached only with `-tags wgextest`. They are linked "
           "into `WGEXEngineTest.xcframework` and developer tests, never into production archives. "
           "Licence texts below come from the vendored tree.\n"]
    for module, (licence, digest) in sorted(TEST_MODULES.items()):
        if module not in versions:
            raise LedgerError(f"test-support module absent from vendor/modules.txt: {module}")
        path = module_dir / "vendor" / module / "LICENSE"
        if sha256(path) != digest:
            raise LedgerError(f"test-support licence changed; review before updating its digest: {module}")
        text = path.read_text(encoding="utf-8").rstrip()
        marker = "Apache License" if licence == "Apache-2.0" else "Redistribution and use in source and binary forms"
        if marker not in text:
            raise LedgerError(f"test-support licence does not match {licence}: {module}")
        out += [f"### {module}\n", f"- Version: `{versions[module]}`",
                f"- Licence: {licence}", f"- Source: `{path.relative_to(ROOT)}`\n",
                "```text\n" + text + "\n```\n"]
    return "\n".join(out)


def windows_section() -> str:
    """Notices for vendored modules that only Windows targets compile."""
    module_dir = ROOT / "Engine/go"
    versions = dict(vendored_versions(module_dir))
    out = ["## Go Windows-only vendored module (not distributed)\n",
           "This vendored module is compiled only for Windows targets. WGEX builds no Windows binary, "
           "so it is not linked into any shipped product; its licence is reproduced because the source "
           "is vendored in `Engine/go/vendor/`.\n"]
    for module, licence in sorted(WINDOWS_MODULES.items()):
        if module not in versions:
            raise LedgerError(f"windows-only module absent from vendor/modules.txt: {module}")
        path = module_dir / "vendor" / module / "LICENSE"
        text = path.read_text(encoding="utf-8").rstrip()
        if licence == "MIT" and "Permission is hereby granted, free of charge" not in text:
            raise LedgerError(f"windows-only licence does not match {licence}: {module}")
        out += [f"### {module}\n", f"- Version: `{versions[module]}`",
                f"- Licence: {licence}", f"- Source: `{path.relative_to(ROOT)}`\n",
                "```text\n" + text + "\n```\n"]
    return "\n".join(out)


def render() -> str:
    rows = parse_ledger()
    parts = [
        HEADER,
        vendored_section(rows),
        engine_test_section(),
        windows_section(),
        go_section(
            "Go modules (distributed)",
            "Engine/go",
            "Reported by `go-licenses report ./...` in `Engine/go`. These modules are linked into the shipped engine archive.",
        ),
        go_section(
            "Go modules (not distributed)",
            "Tools/testpeer",
            "Reported by `go-licenses report ./...` in `Tools/testpeer`. The test peer is a developer tool used for tests only; it is **not distributed** and none of its dependencies ship in any product.",
        ),
    ]
    return "\n".join(p.rstrip() + "\n" for p in parts)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify the ledger and test-support notices; write nothing")
    ap.add_argument("--output", default=str(ROOT / "THIRD_PARTY_NOTICES.md"), help="output path or - for stdout")
    args = ap.parse_args()
    try:
        rows = parse_ledger()
    except LedgerError as exc:
        print(f"notices: ledger error: {exc}", file=sys.stderr)
        return 1
    problems = check_ledger(rows)
    for p in problems:
        print(f"notices: ledger: {p}", file=sys.stderr)
    if problems:
        return 1
    if args.check:
        try:
            notices = (ROOT / "THIRD_PARTY_NOTICES.md").read_text(encoding="utf-8")
            for expected in (engine_test_section().rstrip(), windows_section().rstrip()):
                if expected not in notices:
                    raise LedgerError("test-support or Windows-only notices stale; regenerate THIRD_PARTY_NOTICES.md")
        except (LedgerError, OSError) as exc:
            print(f"notices: {exc}", file=sys.stderr)
            return 1
        print(f"notices: ledger ok ({len(rows)} files)")
        return 0
    text = render()
    if args.output == "-":
        sys.stdout.write(text)
    else:
        Path(args.output).write_text(text, encoding="utf-8")
        print(f"notices: wrote {args.output} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
